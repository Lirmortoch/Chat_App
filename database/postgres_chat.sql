CREATE SCHEMA chat AUTHORIZATION pg_database_owner;

COMMENT ON SCHEMA chat IS 'standard public schema';

-- Drop table

-- DROP TABLE chat.chats;

CREATE TABLE chat.chats (
	id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	"name" varchar(45) NOT NULL,
	url text NULL,
	"type" varchar(25) NOT NULL,
	public_id uuid DEFAULT uuidv7() NOT NULL,
	CONSTRAINT chats_pk PRIMARY KEY (id),
	CONSTRAINT chats_unique_1 UNIQUE (public_id),
	CONSTRAINT chats_url UNIQUE (url)
);
CREATE UNIQUE INDEX chat_public_id_idx ON chat.chats USING btree (public_id);


